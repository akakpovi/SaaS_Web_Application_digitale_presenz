export function getLang(): Lang {
  const stored = localStorage.getItem("presence_lang");
  if (stored && stored in translations) return stored as Lang;
  return "en";
}

export function t(key: string): string {
  const lang = getLang();
  return translations[lang]?.[key] ?? translations["en"]?.[key] ?? key;
}

// Hook legacy — garde compatibilité AppShell/Dashboard existants
import { useState, useEffect } from "react";

export function useT() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const handler = () => setTick((n) => n + 1);
    window.addEventListener("presence_lang_change", handler);
    return () => window.removeEventListener("presence_lang_change", handler);
  }, []);
  return t;
}
